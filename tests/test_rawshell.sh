#!/bin/sh

. tests/include.sh

PROG="$1"

mkdir -p testoutput
TEST=testoutput

TESTNAME="Test rawshell invoked for every telegram, also from unconfigured meters"
TESTRESULT="ERROR"

# One configured meter (12345678), one unconfigured plain meter (33225544)
# and one unconfigured encrypted meter (03065716) without a key.
cat > $TEST/simulation_rawshell.txt <<EOT
telegram=|A244EE4D785634123C067A8F000000|0C1348550000426CE1F14C130000000082046C21298C0413330000008D04931E3A3CFE3300000033000000330000003300000033000000330000003300000033000000330000003300000033000000330000004300000034180000046D0D0B5C2B03FD6C5E150082206C5C290BFD0F0200018C4079678885238310FD3100000082106C01018110FD610002FD66020002FD170000|
telegram=|1844AE4C4455223368077A55000000_041389E20100023B0000|
telegram=|294468501657060394087A4C001025A11E4EFF816C2F8D147ED0C1F959F55E0F0FF724805FCC33D19A19|
EOT

$PROG --format=json --rawshell='echo "$TELEGRAM_ID $TELEGRAM_HEX"' $TEST/simulation_rawshell.txt MWW supercom587 12345678 "" \
      2> $TEST/test_stderr.txt | grep -v '^{' > $TEST/test_output.txt

if [ "$?" = "0" ]
then
    cat > $TEST/test_expected.txt <<EOT
12345678 A244EE4D785634123C067A8F0000000C1348550000426CE1F14C130000000082046C21298C0413330000008D04931E3A3CFE3300000033000000330000003300000033000000330000003300000033000000330000003300000033000000330000004300000034180000046D0D0B5C2B03FD6C5E150082206C5C290BFD0F0200018C4079678885238310FD3100000082106C01018110FD610002FD66020002FD170000
33225544 1844AE4C4455223368077A55000000041389E20100023B0000
03065716 294468501657060394087A4C001025A11E4EFF816C2F8D147ED0C1F959F55E0F0FF724805FCC33D19A19
EOT
    diff $TEST/test_expected.txt $TEST/test_output.txt
    if [ "$?" = "0" ]
    then
        printOK "$TESTNAME"
        TESTRESULT="OK"
    fi
fi

if [ "$TESTRESULT" = "ERROR" ]
then
    printERROR "$TESTNAME"
    exit 1
fi
